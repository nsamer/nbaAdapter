package be.telenet.css.pegacdh.nba.config;

import io.swagger.v3.oas.models.ExternalDocumentation;
import io.swagger.v3.oas.models.OpenAPI;
import io.swagger.v3.oas.models.info.Contact;
import io.swagger.v3.oas.models.info.Info;
import io.swagger.v3.oas.models.parameters.Parameter;
import org.springdoc.core.models.GroupedOpenApi;
import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Configuration;

import java.util.List;

import static be.telenet.css.pegacdh.nba.mapper.NbaRequestMapper.HEADER_BRAND;
import static be.telenet.css.pegacdh.nba.mapper.NbaRequestMapper.HEADER_CORRELATION_ID;
import static be.telenet.css.pegacdh.nba.mapper.NbaRequestMapper.HEADER_MESSAGE_ID;
import static be.telenet.css.pegacdh.nba.mapper.NbaRequestMapper.HEADER_REQUEST_ID;
import static be.telenet.css.pegacdh.nba.mapper.NbaRequestMapper.HEADER_X_SOURCE;

@Configuration
public class SpringDocConfig {

    private static final String DESCRIPTION_UUID = "This is an UUID. It will be autogenerated, if not provided.";
    private static final String DESCRIPTION_BRAND = "This is the consumer brand and possible values are Telenet and Base.";
    private static final String DESCRIPTION_X_SOURCE = "This is the another name of consumer brand, either brand or X-source is mandatory.";
    private static final String PARAMETER_TYPE_HEADER = "header";
    private static final String PARAMETER_TYPE_PATH = "path";
    private static final String PARAMETER_TYPE_QUERY = "query";
    private static final String DESCRIPTION_CUSTOMER_NUMBER = "Customer number";
    private static final String DESCRIPTION_CHANNEL = "This is the digital channel name. Example: Web, FixitAdvisorTool.";
    private static final String DESCRIPTION_DIRECTION = "Possible values of direction are Inbound and Outbound. Inbound will be considered, if not provided.";
    private static final String CUSTOMER_NUMBER = "customerNumber";
    private static final String CHANNEL = "channel";
    private static final String DIRECTION = "direction";

    @Bean
    public GroupedOpenApi applicationApi() {
        return GroupedOpenApi.builder()
                .group("NBA API")
                .pathsToMatch("/v1/customer/**")
                .addOperationCustomizer((operation, handlerMethod) -> operation.parameters(getParameters()))
                .build();
    }

    @Bean
    public GroupedOpenApi actuatorApi() {
        return GroupedOpenApi.builder()
                .group("Actuator API")
                .pathsToMatch("/status/**")
                .build();
    }

    @Bean
    public OpenAPI customOpenApi() {
        return new OpenAPI()
                .info(applicationInfo())
                .externalDocs(externalDocumentation());
    }

    private ExternalDocumentation externalDocumentation() {
        return new ExternalDocumentation().description("Next Best Action (NBA) Adaptor Confluence")
                .url("https://confluence.rel.apps.telenet.be/display/REP/Advisor+Tool+%28Hawking%29+-+2710135");
    }

    private Info applicationInfo() {
        return new Info().title("Next Best Action (NBA) Adaptor")
                .description("Retrieve Next Best Action (NBA) from PEGA")
                .contact(squad());
    }

    private Contact squad() {
        return new Contact().name("Customer Account, PID and Login")
                .email("F_DIFT-Customer_Account_PID_and_Login@telenetgroup.be")
                .url("https://confluence.rel.apps.telenet.be/pages/viewpage.action?pageId=177571413");
    }

    private List<Parameter> getParameters() {
        return List.of(
                new Parameter().in(PARAMETER_TYPE_HEADER).description(DESCRIPTION_UUID).name(HEADER_CORRELATION_ID),
                new Parameter().in(PARAMETER_TYPE_HEADER).description(DESCRIPTION_UUID).name(HEADER_MESSAGE_ID),
                new Parameter().in(PARAMETER_TYPE_HEADER).description(DESCRIPTION_UUID).name(HEADER_REQUEST_ID),
                new Parameter().in(PARAMETER_TYPE_HEADER).description(DESCRIPTION_BRAND).name(HEADER_BRAND),
                new Parameter().in(PARAMETER_TYPE_HEADER).description(DESCRIPTION_X_SOURCE).name(HEADER_X_SOURCE),
                new Parameter().in(PARAMETER_TYPE_PATH).description(DESCRIPTION_CUSTOMER_NUMBER).name(CUSTOMER_NUMBER),
                new Parameter().in(PARAMETER_TYPE_QUERY).description(DESCRIPTION_CHANNEL).name(CHANNEL).required(true),
                new Parameter().in(PARAMETER_TYPE_QUERY).description(DESCRIPTION_DIRECTION).name(DIRECTION)
        );
    }

}
